# -*- coding: utf-8 -*-
"""Compact id -> Chinese/English name map for API-driven pages.

The full item/skill/tree datasets are large (900 KB / 250 KB / 750 KB).  Live
pages such as ladder, meta and build only need names and a few labels, so this
script emits a small index they can load instead.
"""

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "site", "assets", "data")
OUT = os.path.join(DATA, "names.js")

# Terms that only exist in the live API (0.56.8) but are visible on the ladder.
# Official Chinese names are not in the local 0.56.5 files; these follow the
# game's established terminology and are marked as API-only so pages still know
# they are not part of the local gem database.
EXTRA = {
    "skills": {
        "punch": ["徒手", "Bare Fists"],
        "slash": ["斩击", "Slash"],
        "strike": ["劈砍", "Cleave"],
        "arcane_bolt": ["奥术飞弹", "Arcane Bolt"],
        "zap": ["电击", "Zap"],
        "ground_slam": ["震地", "Ground Slam"],
        "leap_slam": ["跃击", "Leap Slam"],
        "ember_bolt": ["余烬箭", "Ember Bolt"],
        "frost_nova": ["冰霜新星", "Frost Nova"],
        "arc": ["电弧", "Chain Lightning"],
        "move": ["移动", "Move"],
        "wayward_orb": ["迷途法球", "Wayward Orb"],
        "thousand_sparks": ["活性法球", "Living Orb"],
    },
    "supports": {
        "kindling_support": ["引燃", "Kindling"],
    },
}


def load(name, var):
    with open(os.path.join(DATA, name), "r", encoding="utf-8") as f:
        text = f.read().strip()
    m = re.match(r"(?:window\.)?%s\s*=\s*([\s\S]*?);?\s*$" % re.escape(var), text)
    if not m:
        raise SystemExit("cannot parse " + name)
    return json.loads(m.group(1))


def p(v, i=0):
    if isinstance(v, str):
        return v
    if isinstance(v, list):
        return v[i] if i < len(v) and v[i] else ""
    return ""


def main():
    items = load("items.js", "BO_ITEMS")
    skills = load("skills.js", "BO_SKILLS")
    tree = load("tree.js", "BO_TREE")
    mobs = load("bestiary.js", "BO_MOBS")

    out = {
        "skills": {},
        "supports": {},
        "nodes": {},
        "dragon": {},
        "uniques": {},
        "bases": {},
        "runes": {},
        "runewords": {},
        "monsters": {},
        "extra": EXTRA,
        "meta": {
            "items": items.get("meta", {}),
            "skills": len(skills.get("skills", [])),
            "supports": len(skills.get("supports", [])),
            "nodes": len(tree.get("nodes", [])),
            "monsters": len(mobs.get("monsters", [])),
            "guardians": len(mobs.get("guardians", [])),
        },
    }

    for s in skills.get("skills", []):
        out["skills"][s.get("id")] = [p(s.get("n")), p(s.get("n"), 1), p(s.get("clsZh")), p(s.get("kindZh")), p(s.get("attrZh"))]
    for s in skills.get("supports", []):
        out["supports"][s.get("id")] = [p(s.get("n")), p(s.get("n"), 1), p(s.get("attrZh"))]

    for n in tree.get("nodes", []):
        out["nodes"][n.get("i")] = [p(n.get("n")), p(n.get("n"), 1), p(n.get("kZh")), p(n.get("g") or "")]

    for c in (tree.get("dragon") or {}).get("classes", []):
        for n in c.get("nodes", []):
            out["dragon"][n.get("i")] = [p(n.get("n")), p(n.get("n"), 1), p(n.get("kZh")), p(n.get("pZh")), c.get("c")]

    for u in items.get("uniques", []):
        out["uniques"][u.get("id")] = [p(u.get("n")), p(u.get("n"), 1), p(u.get("base")), p(u.get("clsZh")), u.get("tier")]

    for b in items.get("bases", []):
        out["bases"][b.get("id")] = [p(b.get("n")), p(b.get("n"), 1), p(b.get("slotZh")), p(b.get("clsZh")), b.get("lvl")]

    for r in items.get("runes", []) + items.get("jewels", []):
        out["runes"][r.get("id")] = [p(r.get("n")), p(r.get("n"), 1), r.get("tier"), r.get("kind")]

    for w in items.get("runewords", []):
        out["runewords"][w.get("id")] = [p(w.get("n")), p(w.get("n"), 1), p(w.get("clsZh")), w.get("sockets")]

    for m in mobs.get("monsters", []) + mobs.get("guardians", []):
        out["monsters"][m.get("id")] = [p(m.get("n")), p(m.get("n"), 1)]

    data = json.dumps(out, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    js = "/* generated by build/build_names.py - do not edit */\nwindow.BO_NAMES=%s;\n" % data
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(js)
    total = sum(len(v) for k, v in out.items() if isinstance(v, dict) and k != "meta")
    print("wrote", OUT, total, "names", len(js.encode("utf-8")), "bytes")


if __name__ == "__main__":
    sys.exit(main())
