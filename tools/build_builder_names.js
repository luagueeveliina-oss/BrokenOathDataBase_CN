const fs = require('fs'), vm = require('vm');
const load = (f, key) => { const c = { window: {}, console }; vm.createContext(c); vm.runInContext(fs.readFileSync(f, 'utf8'), c, { filename: f }); return c.window[key]; };
const PC = load('site/assets/data/planner_core.js', 'BO_PCORE');
const PI = load('site/assets/data/planner_items.js', 'BO_PITEMS');
const PT = load('site/assets/data/planner_tree.js', 'BO_PTREE');
const NM = load('site/assets/data/names.js', 'BO_NAMES');
const out = { class: {}, node: {}, dragon: {}, aspect: {}, base: {}, unique: {}, skill: {}, support: {}, curse: {}, blessing: {}, affixGroup: {} };
const put = (m, id, pair) => { const v = Array.isArray(pair) ? pair[0] : (typeof pair === 'string' ? pair : null); if (v) m[String(id).toLowerCase()] = v; };
for (const c of PC.classes || []) put(out.class, c.id, c.n);
for (const n of PT.nodes || []) put(out.node, n.i, n.n);
for (const [cls, arr] of Object.entries(PT.dragon.classes || {})) for (const n of arr || []) put(out.dragon, n.i, n.n);
for (const a of PT.dragon.aspects || []) put(out.aspect, a.id, a.n);
for (const b of PI.bases || []) put(out.base, b.id, b.n);
for (const u of PI.uniques || []) put(out.unique, u.id, u.n);
for (const a of PI.affixes || []) if (a.grpZh) out.affixGroup[String(a.grp).toLowerCase()] = a.grpZh;
for (const sk of PC.skills || []) put(out.skill, sk.id, sk.n);
for (const sp of PC.supports || []) put(out.support, sp.id, sp.n);
for (const cu of PC.curses || []) put(out.curse, cu.id, cu.n);
for (const bl of PC.blessings || []) put(out.blessing, bl.id, bl.n);
for (const [id, v] of Object.entries((NM && NM.skills) || {})) put(out.skill, id, v);
for (const [id, v] of Object.entries((NM && NM.supports) || {})) put(out.support, id, v);
fs.writeFileSync('site/assets/data/builder_names_zh.js', 'window.BO_ZH = ' + JSON.stringify(out) + ';\n');
console.log(Object.fromEntries(Object.entries(out).map(([k, v]) => [k, Object.keys(v).length])));
